package domainmodel

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
)

// RenderContextMap returns a deterministic Markdown projection of the manifests.
func RenderContextMap(model *DomainModel, capabilities *CapabilityMap, dependencies *DependencyCapabilities) ([]byte, error) {
	if model == nil || capabilities == nil || dependencies == nil {
		return nil, fmt.Errorf("model, capability map, and dependency capabilities must be provided")
	}
	if err := validateDomainModel(model); err != nil {
		return nil, err
	}
	if err := validateCapabilityMap(capabilities); err != nil {
		return nil, err
	}
	if err := validateDependencyCapabilities(dependencies); err != nil {
		return nil, err
	}
	contexts := append([]Context(nil), model.Contexts...)
	sort.Slice(contexts, func(i, j int) bool { return contexts[i].ID < contexts[j].ID })
	relations := append([]Relationship(nil), model.Relationships...)
	sort.Slice(relations, func(i, j int) bool {
		return relations[i].Upstream+"\x00"+relations[i].Downstream < relations[j].Upstream+"\x00"+relations[j].Downstream
	})
	operations := append([]CapabilityOperation(nil), capabilities.Operations...)
	sort.Slice(operations, func(i, j int) bool { return operations[i].Operation < operations[j].Operation })
	var out bytes.Buffer
	out.WriteString("<!-- Code generated by domainmodel.RenderContextMap; DO NOT EDIT. -->\n\n# Domain Context Map\n\n## Subdomains\n\n| Subdomain | Classification | Purpose |\n|---|---|---|\n")
	subdomains := append([]Subdomain(nil), model.Subdomains...)
	sort.Slice(subdomains, func(i, j int) bool { return subdomains[i].ID < subdomains[j].ID })
	for _, s := range subdomains {
		fmt.Fprintf(&out, "| %s | %s | %s |\n", cell(s.ID), cell(s.Classification), cell(s.Purpose))
	}
	out.WriteString("\n## Contexts\n\n| Context | Subdomain | Status | Decision | Confidence | Model | Classification | Owner | Package |\n|---|---|---|---|---|---|---|---|---|\n")
	for _, c := range contexts {
		fmt.Fprintf(&out, "| %s | %s | %s | %s | %s | %s | %s | %s | %s |\n", cell(c.ID), cell(c.Subdomain), cell(c.Status), cell(c.DecisionStatus), cell(c.Confidence), cell(c.ModelKind), cell(c.Classification), cell(orNotVerified(c.Owner)), cell(orNotVerified(c.Package)))
	}
	out.WriteString("\n## Aggregates and Data Ownership\n\n| Context | Aggregate / Resource | Kind | Authority / Consistency Boundary | Owner |\n|---|---|---|---|---|\n")
	for _, c := range contexts {
		for _, a := range c.Aggregates {
			fmt.Fprintf(&out, "| %s | %s | aggregate | %s | %s |\n", cell(c.ID), cell(a.Name), cell(a.ConsistencyBoundary), cell(c.Owner))
		}
		for _, d := range c.DataOwnership {
			fmt.Fprintf(&out, "| %s | %s | data | %s | %s |\n", cell(c.ID), cell(d.Resource), cell(d.Authority), cell(d.Owner))
		}
	}
	out.WriteString("\n## Invariants\n\n| Context | Invariant | Statement |\n|---|---|---|\n")
	for _, c := range contexts {
		invariants := append([]Invariant(nil), c.Invariants...)
		sort.Slice(invariants, func(i, j int) bool { return invariants[i].ID < invariants[j].ID })
		for _, invariant := range invariants {
			fmt.Fprintf(&out, "| %s | %s | %s |\n", cell(c.ID), cell(invariant.ID), cell(invariant.Statement))
		}
	}
	out.WriteString("\n## Relationships\n\n| Upstream | Downstream | Contract | Interaction | Pattern | Decision | Confidence |\n|---|---|---|---|---|---|---|\n")
	for _, r := range relations {
		fmt.Fprintf(&out, "| %s | %s | %s | %s | %s | %s | %s |\n", cell(r.Upstream), cell(r.Downstream), cell(r.Contract), cell(r.Interaction), cell(r.Pattern), cell(r.DecisionStatus), cell(r.Confidence))
	}
	out.WriteString("\n```mermaid\nflowchart LR\n")
	for _, c := range contexts {
		fmt.Fprintf(&out, "    %s[\"%s\\n%s\"]\n", mermaidID(c.ID), mermaidText(c.ID), mermaidText(c.Status))
	}
	for _, r := range relations {
		fmt.Fprintf(&out, "    %s -->|%s / %s / %s / %s / %s| %s\n", mermaidID(r.Upstream), mermaidText(r.Contract), mermaidText(r.Interaction), mermaidText(r.Pattern), mermaidText(r.DecisionStatus), mermaidText(r.Confidence), mermaidID(r.Downstream))
	}
	out.WriteString("```\n\n## Ubiquitous Language\n\n| Context | Term | Definition |\n|---|---|---|\n")
	for _, c := range contexts {
		terms := append([]Term(nil), c.Language...)
		sort.Slice(terms, func(i, j int) bool { return terms[i].Term < terms[j].Term })
		for _, t := range terms {
			fmt.Fprintf(&out, "| %s | %s | %s |\n", cell(c.ID), cell(t.Term), cell(t.Definition))
		}
	}
	out.WriteString("\n## Endpoint Capabilities\n\n| Operation | Status | Capability | Context | Implementation |\n|---|---|---|---|---|\n")
	for _, o := range operations {
		fmt.Fprintf(&out, "| %s | %s | %s | %s | %s |\n", cell(o.Operation), cell(o.Status), cell(o.Capability), cell(orNotVerified(o.Context)), cell(o.CurrentImplementation))
	}
	out.WriteString("\n## Go Module Capability Evidence\n\n| Module | Version | SDK status | Classification | Capabilities | Context signals |\n|---|---|---|---|---|---|\n")
	modules := append([]DependencyCapability(nil), dependencies.Modules...)
	sort.Slice(modules, func(i, j int) bool { return modules[i].Module < modules[j].Module })
	for _, m := range modules {
		fmt.Fprintf(&out, "| %s | %s | %s | %s | %s | %s |\n", cell(m.Module), cell(m.Version), cell(m.CatalogStatus), cell(m.Classification), cell(strings.Join(m.Capabilities, ", ")), cell(orNotVerified(strings.Join(m.Contexts, ", "))))
	}
	return out.Bytes(), nil
}

func cell(value string) string {
	return strings.ReplaceAll(strings.ReplaceAll(value, "|", "\\|"), "\n", " ")
}
func mermaidText(value string) string {
	return strings.ReplaceAll(strings.ReplaceAll(value, "\"", "'"), "\n", " ")
}
func mermaidID(value string) string { return "ctx_" + strings.ReplaceAll(value, "-", "_") }
func orNotVerified(value string) string {
	if value == "" {
		return "Not Verified"
	}
	return value
}
